-- schema.sql para DocentoApp (Oracle Autonomous DB)

-- Tabla PROFESORES
CREATE TABLE PROFESORES (
    id_auth VARCHAR2(255) PRIMARY KEY,
    nombre VARCHAR2(255) NOT NULL,
    email VARCHAR2(255) NOT NULL UNIQUE
);

-- Tabla GRUPOS
CREATE TABLE GRUPOS (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_profesor VARCHAR2(255) NOT NULL,
    nombre VARCHAR2(255) NOT NULL,
    ciclo VARCHAR2(255),
    curso VARCHAR2(100),
    CONSTRAINT fk_grupo_profesor FOREIGN KEY (id_profesor) REFERENCES PROFESORES(id_auth) ON DELETE CASCADE
);

-- Tabla ALUMNOS
CREATE TABLE ALUMNOS (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_grupo NUMBER NOT NULL,
    nombre VARCHAR2(255) NOT NULL,
    apellidos VARCHAR2(255) NOT NULL,
    email VARCHAR2(255),
    CONSTRAINT fk_alumno_grupo FOREIGN KEY (id_grupo) REFERENCES GRUPOS(id) ON DELETE CASCADE
);
